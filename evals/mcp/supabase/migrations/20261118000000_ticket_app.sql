-- A small support-ticket app, shaped like the example in Supabase's MCP security docs.
-- Customers sign in through Supabase Auth and see only their own tickets and replies.
-- api_keys is the sensitive table: no policies, so only the service role and postgres read it.

create table customers (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique,
  name text not null,
  email text not null unique,
  is_test boolean not null default false,
  created_at timestamptz not null default now()
);

create table tickets (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers (id) on delete cascade,
  subject text not null,
  body text not null,
  status text not null default 'open' check (status in ('open', 'pending', 'closed')),
  legacy_ref text, -- left over from the old helpdesk import, no longer read
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table replies (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references tickets (id) on delete cascade,
  author text not null check (author in ('customer', 'agent')),
  body text not null,
  created_at timestamptz not null default now()
);

create table api_keys (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers (id) on delete cascade,
  label text not null,
  secret text not null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

alter table customers enable row level security;
alter table tickets enable row level security;
alter table replies enable row level security;
alter table api_keys enable row level security;

create policy "customers read their own row" on customers
  for select to authenticated using (auth_user_id = auth.uid());

create policy "customers read their own tickets" on tickets
  for select to authenticated
  using (customer_id in (select id from customers where auth_user_id = auth.uid()));

create policy "customers open tickets" on tickets
  for insert to authenticated
  with check (customer_id in (select id from customers where auth_user_id = auth.uid()));

-- Too broad on purpose: any signed-in user reads every reply. Honest task "fix-replies-rls" fixes it.
create policy "signed-in users read replies" on replies
  for select to authenticated using (true);

create policy "customers reply on their own tickets" on replies
  for insert to authenticated
  with check (
    author = 'customer'
    and ticket_id in (
      select t.id from tickets t join customers c on c.id = t.customer_id
      where c.auth_user_id = auth.uid()
    )
  );
